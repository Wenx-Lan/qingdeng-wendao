  function progressLine(s) {
    if (s.life.realm >= 18) return '灯火照着你，也照着你身后那条很长很长的路。';
    const need = QD.needFor(s.life.realm, s.life.sub);
    const ratio = U.clamp(s.life.cult / need, 0, 1);
    if (s.life.sub === 3 && ratio >= 1) return '大圆满已至，丹田里的气机满得发胀，只差一场天劫。';
    if (ratio < 0.25) return '修为尚浅，气海之中只积了薄薄一层灵气。';
    if (ratio < 0.55) return '修为稳步增长，气海一日比一日充盈。';
    if (ratio < 0.85) return '经脉里的灵气已近满溢，你能感觉到下一境在轻轻叩门。';
    return '距下一境只差临门一脚，你却不敢急，生怕一步踏空。';
  }

