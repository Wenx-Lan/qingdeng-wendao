  function advanceText(s, ctx) {
    const out = [];
    const tier = QD.TIER(s.life.realm);
    const A = ctx.actions || {};
    const open = U.pick(REALM_OPEN[s.life.realm]);
    out.push(open + ' ' + progressLine(s));

    const parts = [];
    if (A.closed) parts.push('闭关' + cn(A.closed) + '次');
    if (A.travel) parts.push('下山游历' + cn(A.travel) + '遭');
    if (A.craft) parts.push('在' + jobRoom(s) + '里耗了些时日');
    if (A.feature) parts.push('以心火淬炼己身');
    if (A.dongtian) parts.push('入洞天打理灵田');
    if (parts.length) {
      out.push('这' + periodWord(ctx.years) + '里，你' + parts.join('，') + '。' + actionLine(s, A));
    } else {
      out.push('这' + periodWord(ctx.years) + '里你没有闭关，也没有远行，只是守着洞府看云。');
    }

    if (ctx.pendingTurns >= 2) {
      out.push('宗门那边积了' + cn(ctx.pendingTurns) + '个阶段的弟子物资未领，执事托人捎了话，语气一次比一次客气。');
    }

    out.push(U.pick(FLAVOR[tier]));

    if (s.life.statuses.length) {
      const names = s.life.statuses.map(function (st) { return QD.STATUS[st.id].name; }).join('、');
      out.push('你身上还缠着' + names + '，夜里偶尔会被自己的咳嗽或噩梦惊醒。');
    }

    const omenKey = 'omen_' + s.life.realm;
    if (!s.life.flags[omenKey] && OMENS[s.life.realm]) {
      s.life.flags[omenKey] = true;
      out.push(OMENS[s.life.realm]);
    }

    const need = s.life.realm >= 18 ? 0 : QD.needFor(s.life.realm, s.life.sub);
    const full = need > 0 && s.life.cult >= need;
    if (s.life.sub === 3 && full) {
      out.push('你已站在此境尽头。再往前，便是天劫。');
    } else if (s.life.maxLifespan > 0 && s.life.lifespan / s.life.maxLifespan < 0.2) {
      out.push('寿元将尽的滋味并不好受：你能听见身体里有沙漏在响，一粒，一粒。');
    }

    return out;
  }

